// Generate static SELECT branches from existing projections. No arbitrary SQL at runtime.
import ts from 'typescript';
import fs from 'node:fs';
import { createHash } from 'node:crypto';
const entries=[];
const sources=[
 ['dashboard','app/api/core/dashboard/route.ts',null],
 ['assignments','app/api/core/assignments/route.ts',null],
 ['profile','lib/persistence/student-learning-profile.ts','readStudentLearningProfile'],
 ['coaching','lib/persistence/coaching-center.ts','readCoachingProfileBridge'],
];
for(const [prefix,path,fn] of sources){
 const sf=ts.createSourceFile(path,fs.readFileSync(path,'utf8'),ts.ScriptTarget.Latest,true);
 let count=0;
 function visit(n){
  if(fn && ts.isFunctionDeclaration(n) && n.name?.text!==fn)return;
  let template,bindings=[];
  if(ts.isTaggedTemplateExpression(n)&&n.tag.getText(sf)==='sql'){
   template=n.template;
   if(ts.isTemplateExpression(template))bindings=template.templateSpans.map(s=>s.expression.getText(sf));
  }else if(fn&&ts.isCallExpression(n)&&n.expression.getText(sf)==='sql.query')template=n.arguments[0];
  if(template&&(ts.isNoSubstitutionTemplateLiteral(template)||ts.isTemplateExpression(template))){
   let query=ts.isNoSubstitutionTemplateLiteral(template)?template.text:template.head.text;
   if(ts.isTemplateExpression(template))template.templateSpans.forEach((s,i)=>query+=`$${i+1}`+s.literal.text);
   const normalize=s=>s.replace(/\s+/g,' ').trim();
   const key=createHash('sha256').update(normalize(query)).digest('hex');
   let recipeIndex=-1,timeIndex=-1;
   const replacements=bindings.length?bindings.map((b,i)=>{
    if(b==='student.student_id')return 'v_student';
    if(b==='student.academy_id')return 'v_academy';
    if(b==='student.student_user_id')return 'v_user';
    if(b==='recipeId'){recipeIndex=i;return 'p_recipe';}
    throw Error(`unrecognized binding ${path}: ${b}`);
   }):['v_academy','v_student','p_at'];
   if(!bindings.length&&/\$3\b/.test(query))timeIndex=2;
   const projection=query.replace(/\$(\d+)/g,(_,n)=>replacements[Number(n)-1]??(()=>{throw Error('unbound SQL')})());
   if(!/^\s*(SELECT|WITH)\b/.test(projection)||/\b(INSERT|UPDATE|DELETE|EXECUTE|COPY)\b/i.test(projection))throw Error('not read only');
   entries.push({id:`${prefix}_${++count}`,key,recipeIndex,timeIndex,projection,path});
  }
  ts.forEachChild(n,visit);
 }
 visit(sf);
}
if(entries.length!==17)throw Error(`Expected 17 projections, got ${entries.length}`);
const registry=Object.fromEntries(entries.map(({key,id,recipeIndex,timeIndex})=>[key,{id,recipeIndex,timeIndex}]));
const registryText='// Generated by scripts/qa/build-v03-read-contract.mjs\nexport const qaStudentReads: Record<string, { id: string; recipeIndex: number; timeIndex: number }> = '+JSON.stringify(registry,null,2)+';\n';
const branches=entries.map(e=>`    WHEN '${e.id}' THEN\n      SELECT COALESCE(jsonb_agg(to_jsonb(projected)), '[]'::jsonb) INTO v_result FROM (\n${e.projection}\n      ) projected;`).join('\n');
const sqlText=fs.readFileSync('db/qa/v03-read.template.sql','utf8').replace('-- STATIC_PROJECTIONS',branches);
const outputs=[['lib/qa-student-read-contract.ts',registryText],['db/qa/v03-student-read.sql',sqlText]];
for(const [path,content]of outputs){
 if(process.argv.includes('--check')){if(fs.readFileSync(path,'utf8')!==content)throw Error('projection drift: '+path);}
 else fs.writeFileSync(path,content);
}
console.log(`V03_STATIC_READ_CONTRACT=${entries.length};MATCH=YES`);
